#!/usr/bin/env node
/* WEB-319 — template preview-thumbnail pipeline. For every seed draft in
 * tools/seed-drafts/, renders the harness at desktop (1200x900 clip) and
 * mobile (390x844 clip), converts to webp, uploads to R2
 * template-previews/{key}/{desktop|mobile}.webp on staging + prod, and emits
 * lib/template-previews.ts (the static, cacheable map the picker grid uses).
 * Re-run whenever a seed changes — this script is the regeneration path.
 *
 *   node tools/render-template-previews.mjs [--local]   (local = dev R2 only)
 * Requires the harness worker on :3210 (see check-seed.mjs). */
import { execFile as execFileCb } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFile = promisify(execFileCb);
const appRoot = join(fileURLToPath(import.meta.url), "..", "..");
const HARNESS = process.env.HARNESS_BASE ?? "http://localhost:3210";
const DRAFTS = join(appRoot, "tools", "seed-drafts");
const OUT = join(appRoot, "tools", ".template-previews");

const local = process.argv.includes("--local");
const buckets = local ? ["snap-webcules"] : ["snap-staging", "snap-webcules"];

// desktop 1200x900 + mobile 390x844 viewport-clipped screenshots via the
// shared tools/shot.mjs (mode "clip"), then webp via Pillow.
async function main() {
  if (!existsSync(DRAFTS)) throw new Error("no tools/seed-drafts — author seeds first");
  const { mkdirSync } = await import("node:fs");
  mkdirSync(OUT, { recursive: true });
  const keys = readdirSync(DRAFTS).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();

  const entries = [];
  for (const key of keys) {
    const draft = JSON.parse(readFileSync(join(DRAFTS, `${key}.json`), "utf8"));
    const genre = Array.isArray(draft.genres) && draft.genres[0] ? `&genre=${encodeURIComponent(draft.genres[0])}` : "";
    const accent = draft.harnessAccent ? `&accent=${encodeURIComponent(draft.harnessAccent)}` : "";
    const url = `${HARNESS}/dev/template-harness?design=${encodeURIComponent(JSON.stringify(draft.design))}${genre}${accent}`;
    for (const [label, w, h] of [["desktop", 1200, 900], ["mobile", 390, 844]]) {
      const png = join(OUT, `${key}-${label}.png`);
      await execFile("node", ["tools/shot.mjs", url, png, String(w), String(h), "clip"], { cwd: appRoot });
      const webp = join(OUT, `${key}-${label}.webp`);
      await execFile("python", ["-c", `from PIL import Image; im=Image.open(r"${png}").convert("RGB"); im.save(r"${webp}", "WEBP", quality=78, method=6)`]);
      entries.push({ key, label, webp });
      console.log(`${key}/${label} webp ${Math.round(readFileSync(webp).length / 1024)} KB`);
    }
  }

  for (const bucket of buckets) {
    for (const e of entries) {
      const args = ["wrangler", "r2", "object", "put", `template-previews/${e.key}/${e.label}.webp`.replace(/^/, `${bucket}/`), "--file", e.webp, "--content-type", "image/webp"];
      if (!local) args.push("--remote");
      await execFile("npx", args, { cwd: appRoot, shell: process.platform === "win32" });
    }
    console.log(`uploaded ${entries.length} thumbs to ${bucket}`);
  }

  const byKey = new Map();
  for (const e of entries) {
    const cur = byKey.get(e.key) ?? {};
    cur[e.label] = `/api/pack/template-previews/${e.key}/${e.label}.webp`;
    byKey.set(e.key, cur);
  }
  const ts = `/* GENERATED by tools/render-template-previews.mjs — do not edit.
 * Static, cacheable thumbs for the seed-template picker grid (WEB-319/320):
 * one desktop 1200x900 + mobile 390x844 webp per seed, served immutably from
 * R2 via /api/pack. Regenerate with the tools script after changing a seed. */
export const TEMPLATE_PREVIEWS: Record<string, { desktop: string; mobile: string }> = ${JSON.stringify(Object.fromEntries([...byKey.entries()].sort()), null, 2)};
`;
  writeFileSync(join(appRoot, "lib", "template-previews.ts"), ts);
  const total = entries.reduce((n, e) => n + readFileSync(e.webp).length, 0);
  console.log(`lib/template-previews.ts emitted (${byKey.size} templates, ${(total / 1024 / 1024).toFixed(1)} MB total thumbs)`);
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
